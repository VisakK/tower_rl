"""Posture priors from the demonstrations: IK seeds per (arm, pad, block yaw class, phase).

The data generator seeded its IK with real-robot postures; reusing its joint configurations keeps our IK solutions in
the same (feasible, collision-free) posture families. For every operation in data/subset the measured joint angles
at the grasp, at the highest point of the transport and at the release are grouped by arm, pad (A/B) and block yaw
class (0 / 90 deg, the block being 180 deg symmetric) and averaged. Also records the demos' transport heights.

Writes configs/skills/posture_priors.yaml. Usage: python -I scripts/build_posture_priors.py
"""
import math
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402
import torch  # noqa: E402
import yaml  # noqa: E402

from tower_rl import geometry as geo  # noqa: E402
from tower_rl.data.episode import Episode  # noqa: E402
from tower_rl.data.events import first_lift_frame, operations  # noqa: E402
from tower_rl.kinematics import ArmBase, ArmKinematics  # noqa: E402
from tower_rl.paths import DATA_DIR, REPO_ROOT  # noqa: E402

PADS = {"A": (0.426, -0.277), "B": (0.174, -0.525)}
SL = {"left": slice(0, 7), "back": slice(8, 15)}


def pad_of(xy):
    return min(PADS, key=lambda k: math.dist(PADS[k], xy))


def yaw_class(q_xyzw):
    yaw = math.degrees(float(geo.yaw_from_quat(geo.xyzw_to_wxyz(torch.tensor(q_xyzw, dtype=torch.float64)))))
    y = (yaw + 45) % 180 - 45  # -> [-45, 135)
    return 0 if abs(y) < 45 else 90


def main():
    kin = ArmKinematics(dtype=torch.float64)
    bases = {a: ArmBase(a, dtype=torch.float64) for a in SL}
    groups = defaultdict(list)
    heights = defaultdict(list)
    for f in sorted((DATA_DIR / "subset").glob("*/*.npz")):
        ep = Episode.load(f)
        for op in operations(ep):
            fg = max(op.close_frame, first_lift_frame(ep, op) - 1)
            fr = op.open_frame
            bp_g = ep.block_poses[fg, op.block_index]
            bp_r = ep.block_poses[min(fr + 30, ep.num_frames - 1), op.block_index]
            q = torch.tensor(ep.qpos_obs[:, SL[op.arm]], dtype=torch.float64)
            seg = q[fg:fr]
            p, qq = kin.fk(seg, "pinch")
            pw, _ = bases[op.arm].to_world(p, qq)
            k = int(torch.argmax(pw[:, 2]))
            src_pad, dst_pad = pad_of(bp_g[:2]), pad_of(bp_r[:2])
            groups[(op.arm, "grasp", src_pad, yaw_class(bp_g[3:]))].append(ep.qpos_obs[fg, SL[op.arm]])
            groups[(op.arm, "release", dst_pad, yaw_class(bp_r[3:]))].append(ep.qpos_obs[fr, SL[op.arm]])
            groups[(op.arm, "travel", f"{src_pad}->{dst_pad}", yaw_class(bp_g[3:]))].append(seg[k].numpy())
            heights[(op.arm, f"{src_pad}->{dst_pad}")].append((float(pw[k, 2]), float(pw[0, 2])))
    out = {"note": "mean measured joint angles of the demos (rad), keyed arm -> phase -> pad -> yaw class (deg)",
           "postures": {}, "transport_pinch_height_m": {}}
    for (arm, phase, pad, yc), qs in sorted(groups.items()):
        a = np.stack(qs)
        out["postures"].setdefault(arm, {}).setdefault(phase, {}).setdefault(pad, {})[yc] = {
            "q": [round(float(x), 4) for x in a.mean(0)], "std_max": round(float(a.std(0).max()), 4), "n": len(qs)}
    for (arm, route), hs in sorted(heights.items()):
        a = np.array(hs)
        out["transport_pinch_height_m"].setdefault(arm, {})[route] = {
            "max_mean": round(float(a[:, 0].mean()), 4), "max_min": round(float(a[:, 0].min()), 4),
            "max_max": round(float(a[:, 0].max()), 4), "grasp_mean": round(float(a[:, 1].mean()), 4)}
    path = REPO_ROOT / "configs" / "skills" / "posture_priors.yaml"
    path.write_text("# generated by scripts/build_posture_priors.py from data/subset; do not edit\n" + yaml.safe_dump(out, sort_keys=False, width=140))
    print(yaml.safe_dump(out, sort_keys=False, width=140))


if __name__ == "__main__":
    main()
